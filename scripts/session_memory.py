ID_RE = re.compile(r"^(\d{12}[a-z]?) (.+)\.md$")


class Store:
    """The Zettel/ folder, loaded once: id -> {path, meta, body}."""

    def __init__(self) -> None:
        ensure_dirs()
        self.notes: dict[str, dict] = {}
        for p in sorted(ZETTEL.glob("*.md")):
            m = ID_RE.match(p.name)
            if not m:
                continue
            meta, body = split_frontmatter(p.read_text(encoding="utf-8"))
            self.notes[m.group(1)] = {"path": p, "meta": meta, "body": body,
                                      "title": meta.get("title") or m.group(2)}

    def row(self, zid: str) -> str:
        n = self.notes[zid]
        tags = ",".join(n["meta"].get("tags") or []) if isinstance(n["meta"].get("tags"), list) else ""
        return (f"{zid} | {n['title']} | {n['meta'].get('kind', '')} | "
                f"{n['meta'].get('status', 'active')} | {tags}")

    def catalog(self) -> str:
        """Every zettel as one row. Only backfill still sends this; the writer sends
        retrieved candidates (see candidates_block)."""
        return "\n".join(self.row(z) for z in sorted(self.notes, reverse=True)) or "(no zettels yet)"

    def card(self, zid: str) -> str:
        n = self.notes[zid]
        return f"### {self.row(zid)} | updated {n['meta'].get('updated', '')}\n{n['body'].strip()}"

    def tag_vocab(self, limit: int = 250) -> str:
        """Subject tags by count. Bucket tags are left out: listed first by count,
        they were the ones the writer reused most."""
        counts: dict[str, int] = {}
        buckets = bucket_tags()
        for n in self.notes.values():
            for t in n["meta"].get("tags") or [] if isinstance(n["meta"].get("tags"), list) else []:
                if t not in buckets:
                    counts[t] = counts.get(t, 0) + 1
        top = sorted(counts.items(), key=lambda kv: -kv[1])[:limit]
        return ", ".join(f"{t} ({c})" for t, c in top)

    def candidates(self, query: str) -> tuple[list[str], list[str]]:
        """(full-text tier, title tier) of the zettels nearest to `query`."""
        bm = BM25({z: note_text(n) for z, n in self.notes.items()})
        ranked = [z for z, _ in bm.search(query, k=TITLE_TIER)]
        return ranked[:BODY_TIER], ranked[BODY_TIER:]

    def candidates_block(self, query: str) -> tuple[str, list[str]]:
        body, titles = self.candidates(query)
        if not body:
            return "(no zettels yet)", []
        text = ("Nearest existing zettels, full text (id | title | kind | status | tags):\n\n"
                + "\n\n".join(self.card(z) for z in body))
        if titles:
            text += ("\n\nFurther related zettels, titles only (id | title | kind | status | tags):\n"
                     + "\n".join(self.row(z) for z in titles))
        text += "\n\nTags in use, with counts (reuse these; coin a new tag only for a new subject):\n" + self.tag_vocab()
        return text, body + titles

    def new_id(self, when: dt.datetime) -> str:
        base = f"{local(when):%Y%m%d%H%M}"
        if base not in self.notes:
            return base
        for suffix in "abcdefghijklmnopqrstuvwxyz":
            if base + suffix not in self.notes:
                return base + suffix
        raise RuntimeError(f"id space exhausted for {base}")

    def link(self, zid: str) -> str:
        n = self.notes.get(zid)
        return f"[[{zid} {safe_title(n['title'])}]]" if n else f"[[{zid}]]"

    def create(self, op: dict, when: dt.datetime, source: str) -> Path | None:
        title = safe_title(op.get("title") or "")
        body = str(op.get("body") or "").strip()
        if not title or not body:
            return None
        zid = self.new_id(when)
        kind = op.get("kind") if op.get("kind") in KINDS else "fact"
        status = op.get("status") if op.get("status") in STATUSES else "active"
        tags = norm_tags(op.get("tags"))
        links = norm_links(op.get("links"), self)
        today = f"{local(when):%Y-%m-%d}"
        meta = {"id": zid, "title": title, "type": "zettel", "kind": kind, "tags": tags,
                "status": status, "created": today, "updated": today, "sources": [source]}
        path = ZETTEL / f"{zid} {title}.md"
        path.write_text(render_zettel(meta, body, links), encoding="utf-8")
        self.notes[zid] = {"path": path, "meta": meta, "body": body, "title": title}
        return path

    def update(self, op: dict, when: dt.datetime, source: str) -> Path | None:
        zid = str(op.get("id") or "")
        n = self.notes.get(zid)
        if not n:
            return None
        meta, body = split_frontmatter(n["path"].read_text(encoding="utf-8"))
        body, old_links = split_links(body)
        append = str(op.get("append") or "").strip()
        if append:
            body = body.rstrip() + "\n\n" + f"*{local(when):%Y-%m-%d}:* " + append
        if op.get("status") in STATUSES:
            meta["status"] = op["status"]
        tags = norm_tags(meta.get("tags"))
        for t in norm_tags(op.get("add_tags")):
            if t not in tags:
                tags.append(t)
        meta["tags"] = tags
        raw_sources = meta.get("sources")
        sources: list[str] = list(raw_sources) if isinstance(raw_sources, list) else []
        if source not in sources:
            sources.append(source)
        meta["sources"] = sources
        # `updated` is the date of the last content change (an appended line or a
        # status change). A link-only update leaves it alone: the maintain pass adds
        # links to hundreds of notes, and on 2026-10-15 those bumps made 31 stale open
        # threads look fresh. Never move a zettel backwards in time either (a
        # backfilled older note may touch it).
        if append or op.get("status") in STATUSES:
            meta["updated"] = max(str(meta.get("updated") or ""), f"{local(when):%Y-%m-%d}")
        links = old_links + [ln for ln in norm_links(op.get("links"), self) if ln not in old_links]
        n["path"].write_text(render_zettel(meta, body, links), encoding="utf-8")
        n["meta"], n["body"] = meta, body
        return n["path"]


BUCKETS = ROOT / ".tag-buckets.json"


def bucket_tags() -> set[str]:
    """Tags the maintain pass judged to name a kind of note, not a subject
    ("follow-up", "gotcha"): the kind field already says that."""
    try:
        return set(json.loads(BUCKETS.read_text(encoding="utf-8")))
    except (OSError, json.JSONDecodeError, TypeError):
        return set()


def norm_tags(v) -> list[str]:
    if isinstance(v, str):
        v = [v]
    out = []
    for t in v or []:
        t = re.sub(r"[^a-z0-9-]+", "-", str(t).lower()).strip("-")
        if t and t not in out:
            out.append(t)
    return out[:8]


def norm_links(v, store: Store) -> list[str]:
    out = []
    for item in v or []:
        if isinstance(item, str):
            zid, why = item, ""
        elif isinstance(item, dict):
            zid, why = str(item.get("id") or ""), str(item.get("why") or "").strip()
        else:
            continue
        zid = zid.strip().strip("[]")
        zid = zid.split(" ")[0]
        if zid in store.notes:
            out.append(f"- {store.link(zid)}" + (f" : {why}" if why else ""))
    return out


def split_links(body: str) -> tuple[str, list[str]]:
    """Separate the trailing **Links** list from a zettel body."""
    m = re.search(r"\n\*\*Links\*\*\n", body)
    if not m:
        return body.rstrip(), []
    head, tail = body[:m.start()], body[m.end():]
    links = [ln.rstrip() for ln in tail.splitlines() if ln.startswith("- [[")]
    return head.rstrip(), links


def render_zettel(meta: dict, body: str, links: list[str]) -> str:
    fm = ["---",
          f"id: {yaml_str(meta['id'])}",
          f"title: {yaml_str(meta['title'])}",
          "type: zettel",
          f"kind: {meta.get('kind', 'fact')}",
          f"tags: {yaml_list(meta.get('tags') or [])}",
          f"status: {meta.get('status', 'active')}",
          f"created: {meta.get('created')}",
          f"updated: {meta.get('updated')}",
          f"sources: {yaml_list(meta.get('sources') or [])}",
          "---"]
    out = "\n".join(fm) + "\n" + body.strip() + "\n"
    if links:
        out += "\n**Links**\n" + "\n".join(links) + "\n"
    return out


# --------------------------------------------------------------------------
# retrieval: BM25 over the notes, expanded through embedding neighbors
# --------------------------------------------------------------------------

STOP = frozenset("""the and for that this with from are was were has have had not but you your
its into than then them they their there what when which who will would can could should about
after also any been before being both each just more most only other over same some such very
via per one two all out use used uses new now did does done get got make made how why where
alex mist session note notes zettel""".split())
TOKEN_RE = re.compile(r"[a-z0-9][a-z0-9_.-]*[a-z0-9]|[a-z0-9]")


def tokens(text: str) -> list[str]:
    out = []
    for t in TOKEN_RE.findall(text.lower()):
        if len(t) < 3 or t in STOP or t.isdigit():
            continue
        if len(t) > 4 and t.endswith("s") and not t.endswith("ss"):
            t = t[:-1]
        out.append(t)
    return out


def note_text(n: dict) -> str:
    """What a zettel is indexed and embedded by: title, tags, body without its Links list."""
    tags = n["meta"].get("tags") if isinstance(n["meta"].get("tags"), list) else []
    return f"{n['title']}\n{' '.join(tags or [])}\n{split_links(n['body'])[0]}"


class BM25:
    """Okapi BM25 over id -> text (stdlib only, rebuilt per run: 2,500 notes take
    well under a second)."""

    def __init__(self, docs: dict[str, str], k1: float = 1.2, b: float = 0.75) -> None:
        self.k1, self.b = k1, b
        self.tf: dict[str, dict[str, int]] = {}
        self.dl: dict[str, int] = {}
        df: dict[str, int] = {}
        for zid, text in docs.items():
            counts: dict[str, int] = {}
            for t in tokens(text):
                counts[t] = counts.get(t, 0) + 1
            self.tf[zid] = counts
            self.dl[zid] = sum(counts.values())
            for t in counts:
                df[t] = df.get(t, 0) + 1
        n = max(len(docs), 1)
        self.avgdl = (sum(self.dl.values()) / n) or 1.0
        self.idf = {t: math.log(1 + (n - d + 0.5) / (d + 0.5)) for t, d in df.items()}

    def search(self, query: str, k: int = 30, max_terms: int = 150) -> list[tuple[str, float]]:
        q: dict[str, int] = {}
        for t in tokens(query):
            if t in self.idf:
                q[t] = q.get(t, 0) + 1
        # a long transcript is a bag of terms: keep its most distinctive ones,
        # weighting each by log query frequency so a repeated word cannot dominate
        terms = sorted(q, key=lambda t: -self.idf[t] * (1 + math.log(q[t])))[:max_terms]
        scores: dict[str, float] = {}
        for zid, counts in self.tf.items():
            s = 0.0
            norm = self.k1 * (1 - self.b + self.b * self.dl[zid] / self.avgdl)
            for t in terms:
                f = counts.get(t)
                if f:
                    s += self.idf[t] * (1 + math.log(q[t])) * f * (self.k1 + 1) / (f + norm)
            if s:
                scores[zid] = s
        return sorted(scores.items(), key=lambda kv: -kv[1])[:k]


