def _resolve_title_links(op: dict, titles: dict[str, str]) -> dict:
    """Links given as {"title": ...} name a zettel created in the same reply."""
    links = []
    for ln in op.get("links") or []:
        if isinstance(ln, dict) and ln.get("title") and not ln.get("id"):
            zid = titles.get(safe_title(str(ln["title"])).lower())
            if zid:
                links.append({"id": zid, "why": ln.get("why", "")})
        else:
            links.append(ln)
    return dict(op, links=links)


def apply_ops(store: Store, ops: dict, when: dt.datetime, source: str) -> tuple[list[Path], list[str], list[str]]:
    """Apply a reply's create / update / supersede ops. Creates go first so the
    others can name them by title. Returns (files written, zettel links for the
    session note, ids of existing zettels the reply used)."""
    written: list[Path] = []
    zlinks: list[str] = []
    used: list[str] = []
    titles: dict[str, str] = {}
    orphans = 0
    for op in ops.get("create") or []:
        if not isinstance(op, dict):
            continue
        op = _resolve_title_links(op, titles)
        p = store.create(op, when, source)
        if p:
            zid = p.stem.split(" ")[0]
            titles[safe_title(str(op.get("title") or "")).lower()] = zid
            written.append(p)
            zlinks.append(f"[[{p.stem}]]")
            if not norm_links(op.get("links"), store):
                orphans += 1
    for op in ops.get("update") or []:
        if not isinstance(op, dict):
            continue
        p = store.update(_resolve_title_links(op, titles), when, source)
        if p:
            written.append(p)
            zlinks.append(store.link(str(op.get("id"))))
            used.append(str(op.get("id")))
    for op in ops.get("supersede") or []:
        if not isinstance(op, dict):
            continue
        old = str(op.get("id") or "")
        by = str(op.get("by") or "")
        new = by if by in store.notes else titles.get(safe_title(by).lower())
        if old not in store.notes or not new or new == old:
            continue
        why = str(op.get("why") or "").strip()
        store.update({"id": old, "status": "superseded",
                      "append": f"Superseded by {store.link(new)}" + (f": {why}" if why else "."),
                      "links": [{"id": new, "why": "replaced by"}]}, when, source)
        p = store.update({"id": new, "links": [{"id": old, "why": "replaces"}]}, when, source)
        if p and p not in written:
            written.append(p)
        written.append(store.notes[old]["path"])
        zlinks.append(store.link(old))
        used.append(old)
    if orphans:
        log(f"apply: {orphans} new zettel(s) without a link; the maintain pass links them")
    return written, zlinks, used


def cmd_write(args) -> int:
    ensure_dirs()
    path = Path(args.transcript).expanduser()
    if not path.exists():
        log(f"write: no transcript at {path}")
        return 2
    sid = path.stem
    covered, prev = existing_coverage(sid)
    if prev and not args.force:
        age = time.time() - prev.stat().st_mtime
        if age < REWRITE_COOLDOWN_SEC:
            log(f"write {sid[:8]}: last note {age:.0f}s old, cooling down")
            return 0
    if not acquire_lock(sid):
        log(f"write {sid[:8]}: another writer holds the lock")
        return 0
    try:
        return _write(path, sid, covered, prev, args)
    finally:
        release_lock(sid)


def _write(path: Path, sid: str, covered, prev, args) -> int:
    c = condense(path, since=covered)
    if c["last"] is None:
        log(f"write {sid[:8]}: empty transcript")
        return 0
    if SENTINEL in c["text"][:400]:
        log(f"write {sid[:8]}: one of this writer's own runs, skipped")
        return 0
    if covered and c["last"] <= covered and not args.force:
        log(f"write {sid[:8]}: covered through {covered:%H:%M}, nothing new")
        return 0
    if (c["user_turns"] < MIN_USER_TURNS or c["assistant_chars"] < MIN_ASSISTANT_CHARS) and not args.force:
        log(f"write {sid[:8]}: trivial ({c['user_turns']} turns, {c['assistant_chars']} chars)")
        return 0
    store = Store()
    when = c["last"]
    stamp = f"{local(when):%Y-%m-%d_%H%M}"
    is_delta = prev is not None
    note_name = stamp + ("_delta" if is_delta else "")
    prompt = RULES
    prompt += (f"\n\nSession id {sid}, working directory {c['cwd'] or '?'}, "
               f"{local(c['first']):%Y-%m-%d %H:%M} to {local(when):%H:%M}"
               + (f", model {c['model']}" if c["model"] else "") + ".")
    if is_delta:
        prompt += (f"\n\nAn earlier note ({prev.name}) already covers this session through "
                   f"{local(covered):%H:%M}. Summarize ONLY what happened after that; the "
                   f"transcript below starts there.")
    block, shown = store.candidates_block(c["text"])
    prompt += "\n\n" + block
    prompt += "\n\nThe session:\n\n" + frame(c["text"], f"claude-code-transcript {sid[:8]}")
    if args.dry_run:
        print(prompt)
        return 0
    data = run_claude(prompt, f"write {sid[:8]}")
    if data is None:
        return 1
    if data.get("skip"):
        log(f"write {sid[:8]}: model skipped ({str(data['skip'])[:80]})")
        # Remember the decision so the next compaction does not re-ask.
        _write_skip_marker(sid, when, c["cwd"], str(data["skip"]))
        return 0
    mem = data.get("memory") or {}
    body = str(mem.get("body") or "").strip()
    if not body:
        log(f"write {sid[:8]}: reply had no memory body")
        return 1
    # Reserve the name only after the model call, and atomically: two writers
    # that start in the same minute both saw a free name before the 20-30 s
    # call, and the later one overwrote the earlier note (2026-10-19 12:23).
    note_path = _reserve_note(note_name)
    source = f"[[{note_path.stem}]]"
    ops = data.get("zettels") or {}
    written, zlinks, used = apply_ops(store, ops, when, source)
    log_retrieval("writer", sid, shown, used)
    meta = {"date": f"{local(when):%Y-%m-%d}", "time": f"{local(when):%H:%M}",
            "type": str(mem.get("type") or "conversation"), "title": safe_title(mem.get("title") or ""),
            "session_id": sid, "cwd": c["cwd"], "trigger": args.trigger,
            "covered_through": local(when).isoformat(timespec="seconds"),
            "previous_memory": prev.stem if prev else None, "zettels": zlinks}
    note_path.write_text(render_session(meta, body), encoding="utf-8")
    written.append(note_path)
    flagged = scan(written)
    rebuild_index()
    log(f"write {sid[:8]}: wrote {note_path.name} + {len(zlinks)} zettel op(s)"
        + (f"; SCANNER FLAGGED {len(flagged)} line(s)" if flagged else ""))
    if flagged:
        (LOG_DIR / "injection-scan.log").open("a", encoding="utf-8").write(
            f"[{dt.datetime.now():%Y%m%d_%H%M%S}] session-memory writer output flagged:\n"
            + "".join(f"  {ln}\n" for ln in flagged))
    # A routine save is silent. Only a scanner hit raises a banner.
    if flagged and not args.quiet:
        rel = note_path.relative_to(VAULT).with_suffix("")
        link = "obsidian://open?vault=Exobrain&file=" + str(rel).replace(" ", "%20")
        title = meta["title"] or note_path.stem
        notify(f"Session memory flagged by injection scan: {title}", link, "Basso")
    print(str(note_path))
    return 0


def _reserve_note(note_name: str) -> Path:
    """Create an empty Sessions note under the first free name, atomically."""
    SESSIONS.mkdir(parents=True, exist_ok=True)
    n = 1
    while True:
        path = SESSIONS / (f"{note_name}.md" if n == 1 else f"{note_name}-{n}.md")
        try:
            os.close(os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY))
            return path
        except FileExistsError:
            n += 1


def _write_skip_marker(sid: str, when: dt.datetime, cwd, reason: str) -> None:
    """A zero-content note so coverage tracking knows this session was judged trivial."""
    meta = {"date": f"{local(when):%Y-%m-%d}", "time": f"{local(when):%H:%M}", "type": "skipped",
            "title": "Skipped (trivial session)", "session_id": sid, "cwd": cwd,
            "covered_through": local(when).isoformat(timespec="seconds"), "zettels": []}
    p = SESSIONS / f"{local(when):%Y-%m-%d_%H%M}_skip.md"
    if not p.exists():
        p.write_text(render_session(meta, f"Skipped: {reason}"), encoding="utf-8")


