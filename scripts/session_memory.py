def acquire_lock(session_id: str) -> bool:
    LOCK_DIR.mkdir(parents=True, exist_ok=True)
    lock = LOCK_DIR / session_id
    try:
        lock.mkdir()
    except FileExistsError:
        # a lock older than the claude timeout is a crashed run
        if time.time() - lock.stat().st_mtime > CLAUDE_TIMEOUT_SEC + 60:
            try:
                lock.rmdir()
                lock.mkdir()
            except OSError:
                return False
        else:
            return False
    return True


