SYSTEM_REMINDER = re.compile(r"<system-reminder>.*?</system-reminder>", re.S)
UNTRUSTED_MARK = re.compile(r"<<<(END )?UNTRUSTED[^>]*>>>")


def _block_text(block) -> str:
    if isinstance(block, str):
        return block
    if isinstance(block, dict):
        if block.get("type") == "text":
            return block.get("text") or ""
        if block.get("type") == "tool_use":
            inp = block.get("input")
            s = json.dumps(inp, ensure_ascii=False) if not isinstance(inp, str) else inp
            return f"[tool {block.get('name')}] {s[:TOOL_INPUT_CHARS]}"
        if block.get("type") == "tool_result":
            c = block.get("content")
            if isinstance(c, list):
                c = "\n".join(_block_text(x) for x in c)
            c = str(c or "")
            return f"[result] {c[:TOOL_RESULT_CHARS]}" + ("…" if len(c) > TOOL_RESULT_CHARS else "")
        if block.get("type") == "thinking":
            return ""
    return ""


def _clean(text: str) -> str:
    text = SYSTEM_REMINDER.sub("", text)
    text = UNTRUSTED_MARK.sub("", text)   # a nested frame must not close ours
    return text.strip()


def condense(path: Path, since: dt.datetime | None = None) -> dict:
    """Read a Claude Code transcript and return the parts a summary needs."""
    lines: list[str] = []
    first = last = None
    cwd = model = None
    user_turns = 0
    assistant_chars = 0
    with path.open(encoding="utf-8", errors="replace") as fh:
        for raw in fh:
            try:
                o = json.loads(raw)
            except json.JSONDecodeError:
                continue
            t = o.get("type")
            if t not in ("user", "assistant") or o.get("isSidechain"):
                continue
            ts = parse_iso(o.get("timestamp"))
            if ts is None:
                continue
            cwd = cwd or o.get("cwd")
            msg = o.get("message") or {}
            content = msg.get("content")
            if t == "assistant":
                model = msg.get("model") or model
            blocks = content if isinstance(content, list) else [content]
            is_result = all(isinstance(b, dict) and b.get("type") == "tool_result" for b in blocks
                            if b is not None) and any(isinstance(b, dict) for b in blocks)
            text = _clean("\n".join(_block_text(b) for b in blocks if b is not None))
            if not text:
                continue
            first = first or ts
            last = ts
            if since and ts <= since:
                continue
            if t == "user" and not is_result:
                user_turns += 1
            if t == "assistant":
                assistant_chars += len(text)
            role = "ALEX" if (t == "user" and not is_result) else ("TOOL" if is_result else "MIST")
            lines.append(f"[{local(ts):%H:%M}] {role}: {text}")
    body = "\n\n".join(lines)
    if len(body) > MAX_TRANSCRIPT_CHARS:
        head = int(MAX_TRANSCRIPT_CHARS * 0.2)
        tail = MAX_TRANSCRIPT_CHARS - head
        body = (body[:head] + "\n\n[… middle of the session elided for length …]\n\n"
                + body[-tail:])
    return {"text": body, "first": first, "last": last, "cwd": cwd, "model": model,
            "user_turns": user_turns, "assistant_chars": assistant_chars}


