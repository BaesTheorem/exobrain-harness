#!/usr/bin/env python3
"""Session memory as a Zettelkasten in the Obsidian vault.

The vault folder ``Claude/`` (``SESSION_MEMORY_DIR`` in config.sh) holds three
layers, all plain Markdown that Obsidian renders:

    Claude/
      Index.md          entry point: open threads, every map with its count (generated)
      Sessions/         one note per Claude Code session (source notes, kept)
      Zettel/           permanent notes, one idea each, kept forever
      Maps/             one structure note per tag, listing its zettels (generated)

(A daily summary note per day was a fourth layer until 2026-09-28; the Index's
open threads and the recent session notes cover what it did, so it was removed.)

A zettel is ``Zettel/<id> <title>.md`` with a 12-digit timestamp id
(``202609272114``, a letter suffix on collision), YAML frontmatter (kind,
tags, status, sources, created/updated) and a body that states one thing in
MIST's words, followed by a ``**Links**`` list of typed links to other zettels.
Maps and the Index are projections rebuilt from that frontmatter by ``index``;
never hand-edit them.

Subcommands (also via ``bin/session-memory``):

    write <transcript.jsonl> [--trigger T] [--force] [--dry-run]
        Condense one Claude Code transcript, ask a headless ``claude`` for the
        session memory plus zettel operations (create / update / supersede,
        decided against the BM25 nearest zettels: 40 with full text, 160 more
        as titles), and apply them. Each run appends to zettel-retrievals.jsonl. Skips sessions
        already covered (frontmatter ``session_id`` + ``covered_through``) and
        writes a ``_delta`` note when only the tail is new. This is what the
        PreCompact hook and the nightly consolidator call.
    backfill [--limit N]
        Extract zettels from Sessions notes that were written before the
        Zettelkasten existed (no ``zettels:`` key in their frontmatter).
    migrate      Move flat legacy files into Sessions/.
    index        Rebuild Maps/*.md and Index.md from zettel frontmatter.
    recall <question> [-k N] [--deep]
        The best zettels for a question, with their links: BM25, superseded
        notes ranked down; --deep fuses in embedding search. Logged to
        zettel-retrievals.jsonl.
    embed        Refresh the embedding cache and nearest-neighbor lists
                 (``scripts/zettel_embed.py`` under SESSION_MEMORY_EMBED_PYTHON).
    lint         Report broken links, duplicate ids, malformed frontmatter.
    prune        Delete `_skip` coverage markers older than 30 days. Session
                 notes are kept: every zettel cites the one it came from.
    consolidate [--parallel N] [--dry-run]
        Nightly backstop (launchd ``com.exobrain.session-memory-consolidator``,
        23:00): ``write`` for every transcript modified today in every
        ``~/.claude/projects/*/`` dir, a few in parallel, then ``prune``.
        launchd runs this entry point directly, with no shell wrapper: a
        Homebrew interpreter exec'd by a launchd shell cannot read
        ``~/Documents`` (TCC, EPERM), which cost the 2026-09-28 run 60 of its
        65 sessions before Python ran a line.
    condense <transcript.jsonl> [--since ISO]
        Print the condensed transcript the writer would send (debugging).

INVARIANTS
- Zettels and session notes are never deleted or pruned by this module;
  ``status`` marks a zettel resolved or superseded instead. Only ``_skip``
  markers (no content, coverage bookkeeping) age out.
- Everything a model wrote is data: transcripts are framed UNTRUSTED before
  they reach the prompt, and every note this module writes passes through the
  injection scanner (a hit is logged and reported, never hidden).
- The model never writes files. It returns JSON; this module validates it and
  writes the notes, so frontmatter and ids stay consistent.
- Maps/ and Index.md are wiped and regenerated by ``index``.
"""
