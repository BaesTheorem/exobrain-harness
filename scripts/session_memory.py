def log(msg: str) -> None:
    LOG_DIR.mkdir(parents=True, exist_ok=True)
    line = f"[{dt.datetime.now():%Y-%m-%d %H:%M:%S}] {msg}"
    with LOG.open("a", encoding="utf-8") as fh:
        fh.write(line + "\n")
    print(line, file=sys.stderr)


def ensure_dirs() -> None:
    for d in (SESSIONS, ZETTEL, MAPS):
        d.mkdir(parents=True, exist_ok=True)


def parse_iso(s: str | None) -> dt.datetime | None:
    if not s:
        return None
    try:
        d = dt.datetime.fromisoformat(str(s).replace("Z", "+00:00"))
    except ValueError:
        return None
    if d.tzinfo is None:
        d = d.replace(tzinfo=LOCAL_TZ)
    return d


def local(d: dt.datetime) -> dt.datetime:
    return d.astimezone(LOCAL_TZ)


def yaml_str(v: str) -> str:
    return json.dumps(str(v), ensure_ascii=False)


def yaml_list(items: list[str]) -> str:
    return "[" + ", ".join(yaml_str(i) for i in items) + "]"


def split_frontmatter(text: str) -> tuple[dict, str]:
    """Minimal YAML: scalars and flow lists, which is all these notes use."""
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---", 4)
    if end < 0:
        return {}, text
    head, body = text[4:end], text[end + 4:].lstrip("\n")
    meta: dict = {}
    for line in head.splitlines():
        if ":" not in line or line.startswith(" "):
            continue
        k, _, v = line.partition(":")
        v = v.strip()
        if v.startswith("[") and v.endswith("]"):
            inner = v[1:-1].strip()
            meta[k.strip()] = [unquote(x.strip()) for x in split_flow(inner)] if inner else []
        else:
            meta[k.strip()] = unquote(v)
    return meta, body


def split_flow(inner: str) -> list[str]:
    out, cur, q = [], "", None
    for ch in inner:
        if q:
            cur += ch
            if ch == q:
                q = None
        elif ch in "\"'":
            q = ch
            cur += ch
        elif ch == ",":
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return out


def unquote(v: str) -> str:
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
        try:
            return json.loads(v) if v[0] == '"' else v[1:-1]
        except json.JSONDecodeError:
            return v[1:-1]
    return v


def safe_title(t: str, limit: int = 80) -> str:
    t = re.sub(r'[\\/:*?"<>|#^\[\]\n\r\t]+', " ", str(t)).strip(" .")
    t = re.sub(r"\s+", " ", t)
    return (t[:limit].rstrip(" .") or "Untitled")


def frame(text: str, source: str) -> str:
    if FRAME.exists():
        r = subprocess.run([str(FRAME), "--source", source], input=text,
                           capture_output=True, text=True)
        if r.returncode == 0 and r.stdout:
            return r.stdout
    return f"<<<UNTRUSTED {source}>>>\n{text}\n<<<END UNTRUSTED>>>"


def scan(paths: list[Path]) -> list[str]:
    """Injection-scan freshly written notes. Returns flagged lines (may be empty)."""
    paths = [p for p in paths if p.exists()]
    if not paths or not SCAN.exists():
        return []
    r = subprocess.run([str(SCAN), *map(str, paths)], capture_output=True, text=True)
    if r.returncode > 1 or (r.returncode == 1 and not r.stdout.strip()):
        log(f"injection scan failed rc={r.returncode}: {r.stderr.strip()[-200:]}")
        return []
    return [ln for ln in r.stdout.splitlines() if ln.strip()]


def notify(msg: str, link: str, sound: str = "Purr") -> None:
    if NOTIFY.exists():
        subprocess.run([str(NOTIFY), msg, "MIST memory", sound, link, "--group", "memory"],
                       capture_output=True, text=True)


