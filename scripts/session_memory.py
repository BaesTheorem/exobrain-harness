def cmd_backfill(args) -> int:
    ensure_dirs()
    todo = [(p, m) for p, m in session_notes()
            if "zettels" not in m and m.get("type") != "skipped" and not p.stem.endswith("_skip")]
    if args.limit:
        todo = todo[: args.limit]
    if not todo:
        log("backfill: nothing to do")
        return 0
    # group by day so each model call sees one day's notes together
    days: dict[str, list[tuple[Path, dict]]] = {}
    for p, m in todo:
        days.setdefault(p.name[:10], []).append((p, m))
    log(f"backfill: {len(todo)} notes over {len(days)} day(s)")
    done = 0
    for i, (day, notes) in enumerate(sorted(days.items()), 1):
        store = Store()
        parts = [f"### {p.stem}\n" + p.read_text(encoding="utf-8") for p, _ in notes]
        prompt = (BACKFILL_RULES + "\n\nExisting zettel catalog (id | title | kind | status | tags):\n"
                  + store.catalog() + "\n\nSession notes:\n\n" + frame("\n\n".join(parts), "session-notes"))
        print(f"[{i}/{len(days)}] {day}: {len(notes)} notes", file=sys.stderr)
        data = run_claude(prompt, f"backfill {day}")
        if not data:
            continue
        by_stem = {p.stem: (p, m) for p, m in notes}
        for item in data.get("notes") or []:
            if not isinstance(item, dict):
                continue
            stem = str(item.get("note") or "")
            if stem not in by_stem:
                continue
            p, m = by_stem[stem]
            when = parse_iso(m.get("covered_through")) or dt.datetime.strptime(
                p.name[:15], "%Y-%m-%d_%H%M").replace(tzinfo=LOCAL_TZ)
            source = f"[[{stem}]]"
            zlinks: list[str] = []
            titles: dict[str, str] = {}
            for op in item.get("update") or []:
                if isinstance(op, dict) and store.update(op, when, source):
                    zlinks.append(store.link(str(op.get("id"))))
            for op in item.get("create") or []:
                if not isinstance(op, dict):
                    continue
                # links by title refer to zettels created earlier in this reply
                links = []
                for ln in op.get("links") or []:
                    if isinstance(ln, dict) and ln.get("title") and not ln.get("id"):
                        zid = titles.get(safe_title(ln["title"]).lower())
                        if zid:
                            links.append({"id": zid, "why": ln.get("why", "")})
                    else:
                        links.append(ln)
                op = dict(op, links=links)
                zp = store.create(op, when, source)
                if zp:
                    zlinks.append(f"[[{zp.stem}]]")
                    titles[safe_title(str(op.get("title") or "")).lower()] = zp.stem.split(" ")[0]
                    when = when + dt.timedelta(seconds=1)   # distinct ids within one note
            # record the extraction on the source note
            text = p.read_text(encoding="utf-8")
            meta, body = split_frontmatter(text)
            meta["zettels"] = zlinks
            p.write_text(render_legacy(meta, body), encoding="utf-8")
            done += 1
        rebuild_index()
    log(f"backfill: processed {done} notes")
    return 0


def render_legacy(meta: dict, body: str) -> str:
    """Re-serialize an older session note, keeping its keys and adding zettels."""
    fm = ["---"]
    for k, v in meta.items():
        if k == "zettels":
            continue
        fm.append(f"{k}: {yaml_list(v) if isinstance(v, list) else yaml_str(v)}")
    fm.append(f"zettels: {yaml_list(meta.get('zettels') or [])}")
    fm.append("---")
    return "\n".join(fm) + "\n" + body.strip() + "\n"


def cmd_migrate(_args) -> int:
    ensure_dirs()
    moved = 0
    for p in sorted(ROOT.glob("*.md")):
        if p.name == INDEX.name:
            continue
        if p.name.endswith("_DIGEST.md") or not re.match(r"^\d{4}-\d{2}-\d{2}_", p.name):
            continue
        dest = SESSIONS / p.name
        if dest.exists():
            continue
        p.rename(dest)
        moved += 1
    log(f"migrate: moved {moved} file(s) into Sessions/")
    rebuild_index()
    return 0


def rebuild_index() -> None:
    """Maps/<tag>.md and Index.md are projections of zettel frontmatter."""
    store = Store()
    MAPS.mkdir(parents=True, exist_ok=True)
    for old in MAPS.glob("*.md"):
        old.unlink()
    by_tag: dict[str, list[str]] = {}
    by_kind: dict[str, int] = {}
    open_threads: list[tuple[str, str]] = []   # (updated, row)
    for zid, n in sorted(store.notes.items(), reverse=True):
        meta = n["meta"]
        by_kind[meta.get("kind", "fact")] = by_kind.get(meta.get("kind", "fact"), 0) + 1
        tags = meta.get("tags") if isinstance(meta.get("tags"), list) else []
        row = (f"- {store.link(zid)}" + (f" ({meta.get('status')})" if meta.get("status") not in (None, "active") else "")
               + f" · {meta.get('kind', '')} · {meta.get('updated', '')}")
        for t in tags or ["untagged"]:
            by_tag.setdefault(t, []).append(row)
        if meta.get("kind") == "open-thread" and meta.get("status", "active") == "active":
            open_threads.append((str(meta.get("updated") or ""), row))
    header = ("<!-- generated by scripts/session_memory.py index; edit zettel frontmatter, not this file -->\n")
    for tag, rows in by_tag.items():
        (MAPS / f"{tag}.md").write_text(
            f"---\ntype: map\ntag: {yaml_str(tag)}\ncount: {len(rows)}\n---\n{header}"
            f"# {tag}\n\n" + "\n".join(rows) + "\n", encoding="utf-8")
    lines = ["---", "type: index", f"updated: {dt.datetime.now(LOCAL_TZ).isoformat(timespec='seconds')}",
             f"zettels: {len(store.notes)}", "---", header.rstrip(),
             "# MIST memory",
             "",
             "Sessions/ are source notes (kept), Zettel/ the permanent ideas, Structure/ "
             "the topic hubs, Maps/ one full list per tag. Search with "
             "`bin/session-memory recall`; health in [[Health]]. See the /session-memory skill.",
             "",
             "## Open threads",
             *open_thread_rows(open_threads),
             "",
             *register_rows(by_tag),
             "",
             "## Kinds",
             *(f"- {k}: {v}" for k, v in sorted(by_kind.items())),
             "",
             "## Recent zettels",
             *(f"- {store.link(z)}" for z in sorted(store.notes, reverse=True)[:25]),
             ""]
    INDEX.write_text("\n".join(lines), encoding="utf-8")


STRUCTURE = ROOT / "Structure"
REGISTER_MAPS = 40


def register_rows(by_tag: dict[str, list[str]]) -> list[str]:
    """The Index's register, sparse the way Luhmann's was (a few pointers per
    keyword, the links lead on): structure notes with their entry points, then
    the largest subject maps that have none. Bucket tags are left out."""
    buckets = bucket_tags()
    rows, covered = [], set()
    structs = []
    for p in sorted(STRUCTURE.glob("*.md")) if STRUCTURE.exists() else []:
        meta, _ = split_frontmatter(p.read_text(encoding="utf-8"))
        structs.append((len(by_tag.get(p.stem, [])), p.stem, meta.get("entry") or []))
    if structs:
        # One short line per topic: the Index loads into every session, and with four
        # full-title entry links per row it reached 36 KB for 78 topics. The entry
        # points live in each structure note.
        rows += ["## Register", "Structure notes, each an overview with a few entry points: "
                 + " · ".join(f"[[Structure/{tag}|{tag}]] ({count})"
                              for count, tag, _ in sorted(structs, reverse=True)), ""]
        covered.update(tag for _, tag, _ in structs)
    rest = [(t, r) for t, r in sorted(by_tag.items(), key=lambda kv: -len(kv[1]))
            if t not in covered and t not in buckets]
    rows += ["## Maps", *(f"- [[Maps/{t}|{t}]] ({len(r)})" for t, r in rest[:REGISTER_MAPS])]
    if len(rest) > REGISTER_MAPS:
        rows.append(f"- and {len(rest) - REGISTER_MAPS} smaller maps in Maps/")
    return rows


OPEN_THREAD_DAYS = 14
OPEN_THREAD_MAX = 30


def open_thread_rows(items: list[tuple[str, str]]) -> list[str]:
    """The Index is loaded into every session, so it lists only the open threads
    touched in the last two weeks (newest first, capped) and counts the rest;
    the older ones stay reachable through Maps/ and rg."""
    if not items:
        return ["- none"]
    cutoff = f"{dt.datetime.now(LOCAL_TZ) - dt.timedelta(days=OPEN_THREAD_DAYS):%Y-%m-%d}"
    items = sorted(items, reverse=True)
    recent = [row for upd, row in items if upd >= cutoff][:OPEN_THREAD_MAX]
    rest = len(items) - len(recent)
    return (recent or ["- none in the last two weeks"]) + (
        [f"- and {rest} older open thread(s), see the maps"] if rest else [])


def cmd_embed(_args) -> int:
    """Refresh the embedding cache and neighbors.json (only changed notes re-embed)."""
    store = Store()
    if not Path(EMBED_PYTHON).exists():
        log(f"embed: no embedder interpreter at {EMBED_PYTHON}; neighbors stay as they are")
        return 0
    EMBED_CACHE.mkdir(parents=True, exist_ok=True)
    docs = EMBED_CACHE / "docs.jsonl"
    docs.write_text("".join(json.dumps({"id": z, "text": note_text(n)}) + "\n"
                            for z, n in sorted(store.notes.items())), encoding="utf-8")
    try:
        r = subprocess.run([EMBED_PYTHON, str(EMBED_SCRIPT), "index", str(docs), str(EMBED_CACHE)],
                           capture_output=True, text=True, timeout=1800)
    except subprocess.TimeoutExpired:
        # The notes are written before this step; a slow embed (a busy Mac on
        # 2026-10-25) must not fail the whole run. zettel_embed.py keeps a
        # checkpoint, so the next run continues where this one stopped.
        log("embed: timed out after 1800 s; the checkpoint keeps the vectors made so far")
        return 124
    tail = (r.stderr or "").strip().splitlines()
    log(f"embed: exit {r.returncode}: {tail[-1] if tail else ''}")
    return r.returncode


def recall(query: str, k: int = 8, deep: bool = False) -> list[str]:
    store = Store()
    hits = BM25({z: note_text(n) for z, n in store.notes.items()}).search(query, k=100)
    ranked = rerank(hits, recall_features(store))
    if deep and Path(EMBED_PYTHON).exists() and (EMBED_CACHE / "keys.json").exists():
        r = subprocess.run([EMBED_PYTHON, str(EMBED_SCRIPT), "query", str(EMBED_CACHE), "100", query],
                           capture_output=True, text=True, timeout=300)
        try:
            emb = [z for z in json.loads(r.stdout) if z in store.notes]
        except json.JSONDecodeError:
            emb = []
        fused: dict[str, float] = {}
        for lst in (ranked, emb):
            for i, z in enumerate(lst):
                fused[z] = fused.get(z, 0.0) + 1.0 / (60 + i)
        ranked = sorted(fused, key=lambda z: -fused[z])
    return ranked[:k]


def cmd_recall(args) -> int:
    """Print the best zettels for a question, each with its links (one hop on)."""
    query = " ".join(args.query)
    ids = recall(query, k=args.k, deep=args.deep)
    store = Store()
    log_retrieval("recall", query[:200], ids, [])
    if not ids:
        print("no zettel matches; try other words, or rg -il '<term>' the Zettel folder")
        return 1
    for z in ids:
        n = store.notes[z]
        body, links = split_links(n["body"])
        print(f"## {store.row(z)} | updated {n['meta'].get('updated', '')}")
        print(f"   {n['path']}")
        print(body.strip()[: args.chars])
        if links:
            print("   links: " + " | ".join(ln[2:] for ln in links[:6]))
        print()
    return 0


