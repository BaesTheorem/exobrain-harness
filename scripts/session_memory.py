ID_RE = re.compile(r"^(\d{12}[a-z]?) (.+)\.md$")


class Store:
    """The Zettel/ folder, loaded once: id -> {path, meta, body}."""

    def __init__(self) -> None:
        ensure_dirs()
        self.notes: dict[str, dict] = {}
        for p in sorted(ZETTEL.glob("*.md")):
            m = ID_RE.match(p.name)
            if not m:
                continue
            meta, body = split_frontmatter(p.read_text(encoding="utf-8"))
            self.notes[m.group(1)] = {"path": p, "meta": meta, "body": body,
                                      "title": meta.get("title") or m.group(2)}

    def catalog(self) -> str:
        rows = []
        for zid, n in sorted(self.notes.items(), reverse=True):
            tags = ",".join(n["meta"].get("tags") or []) if isinstance(n["meta"].get("tags"), list) else ""
            rows.append(f"{zid} | {n['title']} | {n['meta'].get('kind', '')} | "
                        f"{n['meta'].get('status', 'active')} | {tags}")
        return "\n".join(rows) or "(no zettels yet)"

    def new_id(self, when: dt.datetime) -> str:
        base = f"{local(when):%Y%m%d%H%M}"
        if base not in self.notes:
            return base
        for suffix in "abcdefghijklmnopqrstuvwxyz":
            if base + suffix not in self.notes:
                return base + suffix
        raise RuntimeError(f"id space exhausted for {base}")

    def link(self, zid: str) -> str:
        n = self.notes.get(zid)
        return f"[[{zid} {safe_title(n['title'])}]]" if n else f"[[{zid}]]"

    def create(self, op: dict, when: dt.datetime, source: str) -> Path | None:
        title = safe_title(op.get("title") or "")
        body = str(op.get("body") or "").strip()
        if not title or not body:
            return None
        zid = self.new_id(when)
        kind = op.get("kind") if op.get("kind") in KINDS else "fact"
        status = op.get("status") if op.get("status") in STATUSES else "active"
        tags = norm_tags(op.get("tags"))
        links = norm_links(op.get("links"), self)
        today = f"{local(when):%Y-%m-%d}"
        meta = {"id": zid, "title": title, "type": "zettel", "kind": kind, "tags": tags,
                "status": status, "created": today, "updated": today, "sources": [source]}
        path = ZETTEL / f"{zid} {title}.md"
        path.write_text(render_zettel(meta, body, links), encoding="utf-8")
        self.notes[zid] = {"path": path, "meta": meta, "body": body, "title": title}
        return path

    def update(self, op: dict, when: dt.datetime, source: str) -> Path | None:
        zid = str(op.get("id") or "")
        n = self.notes.get(zid)
        if not n:
            return None
        meta, body = split_frontmatter(n["path"].read_text(encoding="utf-8"))
        body, old_links = split_links(body)
        append = str(op.get("append") or "").strip()
        if append:
            body = body.rstrip() + "\n\n" + f"*{local(when):%Y-%m-%d}:* " + append
        if op.get("status") in STATUSES:
            meta["status"] = op["status"]
        tags = norm_tags(meta.get("tags"))
        for t in norm_tags(op.get("add_tags")):
            if t not in tags:
                tags.append(t)
        meta["tags"] = tags
        raw_sources = meta.get("sources")
        sources: list[str] = list(raw_sources) if isinstance(raw_sources, list) else []
        if source not in sources:
            sources.append(source)
        meta["sources"] = sources
        # never move a zettel backwards in time (a backfilled older note may touch it)
        meta["updated"] = max(str(meta.get("updated") or ""), f"{local(when):%Y-%m-%d}")
        links = old_links + [ln for ln in norm_links(op.get("links"), self) if ln not in old_links]
        n["path"].write_text(render_zettel(meta, body, links), encoding="utf-8")
        n["meta"], n["body"] = meta, body
        return n["path"]


def norm_tags(v) -> list[str]:
    if isinstance(v, str):
        v = [v]
    out = []
    for t in v or []:
        t = re.sub(r"[^a-z0-9-]+", "-", str(t).lower()).strip("-")
        if t and t not in out:
            out.append(t)
    return out[:8]


def norm_links(v, store: Store) -> list[str]:
    out = []
    for item in v or []:
        if isinstance(item, str):
            zid, why = item, ""
        elif isinstance(item, dict):
            zid, why = str(item.get("id") or ""), str(item.get("why") or "").strip()
        else:
            continue
        zid = zid.strip().strip("[]")
        zid = zid.split(" ")[0]
        if zid in store.notes:
            out.append(f"- {store.link(zid)}" + (f" : {why}" if why else ""))
    return out


def split_links(body: str) -> tuple[str, list[str]]:
    """Separate the trailing **Links** list from a zettel body."""
    m = re.search(r"\n\*\*Links\*\*\n", body)
    if not m:
        return body.rstrip(), []
    head, tail = body[:m.start()], body[m.end():]
    links = [ln.rstrip() for ln in tail.splitlines() if ln.startswith("- [[")]
    return head.rstrip(), links


def render_zettel(meta: dict, body: str, links: list[str]) -> str:
    fm = ["---",
          f"id: {yaml_str(meta['id'])}",
          f"title: {yaml_str(meta['title'])}",
          "type: zettel",
          f"kind: {meta.get('kind', 'fact')}",
          f"tags: {yaml_list(meta.get('tags') or [])}",
          f"status: {meta.get('status', 'active')}",
          f"created: {meta.get('created')}",
          f"updated: {meta.get('updated')}",
          f"sources: {yaml_list(meta.get('sources') or [])}",
          "---"]
    out = "\n".join(fm) + "\n" + body.strip() + "\n"
    if links:
        out += "\n**Links**\n" + "\n".join(links) + "\n"
    return out


